#!/bin/bash
# Wraps the official postgres docker-entrypoint.sh and enforces TLS for all
# TCP connections:
#   * ssl=on, TLS >= 1.2, server certificate from $PG_TLS_CERT_FILE/$PG_TLS_KEY_FILE
#   * pg_hba: local (unix socket) trust, hostnossl rejected, hostssl password auth
#   * no client certificates are requested (no ssl_ca_file)
# Fails closed if a variable is unset or the certificate/key cannot be read.
#
# Environment (required, no defaults):
#   PG_TLS_CERT_FILE     server certificate (set by docker compose)
#   PG_TLS_KEY_FILE      private key (set by docker compose)
#   PG_TLS_RUNTIME_DIR   copy target (set in the image)
# Optional:
#   POSTGRES_HOST_AUTH_METHOD [scram-sha-256] auth method for hostssl lines
set -euo pipefail

#Only wrap the server itself; psql, pg_restore, bash ... pass straight through.
if [ "${1:-postgres}" != "postgres" ] && [ "${1:0:1}" != "-" ]; then
    exec docker-entrypoint.sh "$@"
fi
if [ "${1:-}" = "postgres" ]; then
    shift
fi

#
cert="$PG_TLS_CERT_FILE"
key="$PG_TLS_KEY_FILE"
runtime="$PG_TLS_RUNTIME_DIR"

mkdir -p "$runtime"
install -m 0644 "$cert" "$runtime/server.crt"
install -m 0600 "$key" "$runtime/server.key"
cat > "$runtime/pg_hba.conf" <<HBA
# Generated by tls-entrypoint.sh (ALTLAGA-10) - TLS is mandatory for TCP connections.
# TYPE     DATABASE  USER  ADDRESS  METHOD
local      all       all            trust
hostnossl  all       all   all      reject
hostssl    all       all   all      scram-sha-256
HBA
chmod 0644 "$runtime/pg_hba.conf"
if [ "$(id -u)" = 0 ]; then
    chown -R postgres:postgres "$runtime"
    chmod 0700 "$runtime"
fi

exec docker-entrypoint.sh postgres \
    -c ssl=on \
    -c ssl_cert_file="$runtime/server.crt" \
    -c ssl_key_file="$runtime/server.key" \
    -c ssl_min_protocol_version=TLSv1.2 \
    -c hba_file="$runtime/pg_hba.conf" \
    "$@"
